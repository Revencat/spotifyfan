/** Renders original demo audio offline and stores it like any local import. */
export async function installDemoLibrary(): Promise<Track[]> {
  const tracks: Track[] = [];
  for (const d of DEMO_DEFS) {
    const blob = await renderDemoAudio(d);
    const id = `local-demo-${d.seed}`;
    await idbPutAudio(id, blob);
    tracks.push({
      id, source: 'local', sourceId: `demo:${d.seed}`,
      title: d.title, artist: d.artist, album: d.album, genre: d.genre, year: d.year,
      durationSec: d.dur, coverUrl: generateCover(`${d.title}|${d.artist}`),
      addedAt: Date.now(), license: 'Original demo audio generated by SONORA',
    });
  }
  return tracks;
}

async function renderDemoAudio(d: DemoDef): Promise<Blob> {
  const sr = 22050;
  const ctx = new OfflineAudioContext(1, sr * d.dur, sr);
  const master = ctx.createGain();
  master.gain.value = 0.7;
  master.connect(ctx.destination);

  // pad chord
  const chordRoots = [220, 174.6, 196, 164.8];
  const root = chordRoots[d.seed % 4];
  const scale = [1, 9 / 8, 5 / 4, 3 / 2, 5 / 3];

  for (let i = 0; i < 3; i++) {
    const o = ctx.createOscillator();
    o.type = i === 0 ? 'sine' : 'triangle';
    o.frequency.value = root * scale[(i + d.seed) % 5] * (i === 2 ? 2 : 1);
    const g = ctx.createGain();
    g.gain.setValueAtTime(0, 0);
    g.gain.linearRampToValueAtTime(0.12, 2);
    g.gain.setValueAtTime(0.12, d.dur - 3);
    g.gain.linearRampToValueAtTime(0, d.dur);
    // slow vibrato
    const lfo = ctx.createOscillator();
    lfo.frequency.value = 0.1 + (d.seed % 7) * 0.03;
    const lg = ctx.createGain();
    lg.gain.value = 1.5;
    lfo.connect(lg).connect(o.frequency);
    lfo.start(0);
    o.connect(g).connect(master);
    o.start(0); o.stop(d.dur);
  }

  if (d.mood !== 'ambient') {
    // rhythmic pulses / arpeggios
    const bpm = d.mood === 'pulse' ? 100 : 84;
    const beat = 60 / bpm;
    for (let t = 2; t < d.dur - 2; t += beat) {
      const o = ctx.createOscillator();
      o.type = 'square';
      const step = scale[Math.floor(((t / beat) + d.seed) % 5)];
      o.frequency.value = root * 2 * (d.mood === 'arpeggio' ? step : 1);
      const g = ctx.createGain();
      g.gain.setValueAtTime(0.0001, t);
      g.gain.exponentialRampToValueAtTime(0.06, t + 0.02);
      g.gain.exponentialRampToValueAtTime(0.0001, t + beat * 0.6);
      const f = ctx.createBiquadFilter();
      f.type = 'lowpass';
      f.frequency.value = 2400;
      o.connect(f).connect(g).connect(master);
      o.start(t); o.stop(t + beat);
    }
  }

  const buf = await ctx.startRendering();
  return audioBufferToWav(buf);
}

function audioBufferToWav(b: AudioBuffer): Blob {
  const ch = b.getChannelData(0);
  const len = ch.length;
  const ab = new ArrayBuffer(44 + len * 2);
  const v = new DataView(ab);
  const ws = (o: number, s: string) => { for (let i = 0; i < s.length; i++) v.setUint8(o + i, s.charCodeAt(i)); };
  ws(0, 'RIFF'); v.setUint32(4, 36 + len * 2, true); ws(8, 'WAVE'); ws(12, 'fmt ');
  v.setUint32(16, 16, true); v.setUint16(20, 1, true); v.setUint16(22, 1, true);
  v.setUint32(24, b.sampleRate, true); v.setUint32(28, b.sampleRate * 2, true);
  v.setUint16(32, 2, true); v.setUint16(34, 16, true); ws(36, 'data'); v.setUint32(40, len * 2, true);
  let off = 44;
  for (let i = 0; i < len; i++, off += 2) {
    const s = Math.max(-1, Math.min(1, ch[i]));
    v.setInt16(off, s < 0 ? s * 0x7fff : s * 0x7fff, true);
  }
  return new Blob([ab], { type: 'audio/wav' });
}
